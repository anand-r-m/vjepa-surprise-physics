#!/usr/bin/env python3
"""Replace {{key|fmt}} and \\num{TBD:key} in paper/sections/*.tex by literal values
from results/VERIFIED.json and write paper/NUMBER_TRACE.md.
fmt: (none)=display or value | N = round to N decimals | sN = signed, N decimals |
ciN = 'lo to hi' with N decimals | pN = percent sign appended handled in text."""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
V = {e['key']: e for e in json.load(open(root/'results/VERIFIED.json'))['entries']}
trace = []
def num(x, n, signed=False):
    from decimal import Decimal, ROUND_HALF_UP  # one rule: round half up on the stored value
    q = Decimal(repr(float(x))).quantize(Decimal(1).scaleb(-n), ROUND_HALF_UP)
    s = f"{abs(q):f}"
    if q < 0: return "$-$" + s
    return ("+" + s) if signed else s
def tex(s):
    s = re.sub(r'(\d(?:\.\d+)?)e-(\d+)', r'$\1\\times10^{-\2}$', s)
    s = re.sub(r'^<\s*', '$<$', s)
    s = re.sub(r'^-(\d)', r'$-$\1', s)
    s = s.replace(' to -', ' to $-$')
    return s
def render(key, fmt):
    e = V[key]
    if fmt is None:
        d = e.get('display'); d = d if d is not None else e['value']
        return tex(str(d))
    if fmt.startswith('ci'):
        lo, hi = e['ci']; n = int(fmt[2:]); return f"{num(lo,n)} to {num(hi,n)}"
    if fmt.startswith('s'): return num(e['value'], int(fmt[1:]), True)
    if fmt.startswith('v') and fmt[1:].isdigit():  # value-as-list element not used
        raise ValueError
    return num(e['value'], int(fmt))
pat = re.compile(r'\{\{([^}|]+)(?:\|([^}]+))?\}\}|\\num\{TBD:([^}]+)\}')
for f in sorted((root/'paper/sections').glob('*.tex')):
    out = []
    for i, line in enumerate(f.read_text().split('\n'), 1):
        def sub(m):
            key = m.group(1) or m.group(3); fmt = m.group(2)
            if key not in V or V[key]['status'] in ('pending',):
                sys.exit(f"BAD key {key} in {f.name}:{i}")
            r = render(key, fmt)
            e = V[key]
            trace.append((f.name, i, key, fmt or '', r, e['status'], ', '.join(e.get('sources', []))))
            return r
        out.append(pat.sub(sub, line))
    f.write_text('\n'.join(out))
old = (root/'paper/NUMBER_TRACE.md').read_text() if (root/'paper/NUMBER_TRACE.md').exists() else ''
head = old.split('\n## Trace')[0] if '## Trace' in old else old
lines = [head.rstrip(), '', '## Trace (auto-generated by paper/fill_numbers.py; file:line, VERIFIED key, format, rendered, status, run IDs)', '',
         '| file:line | key | fmt | rendered | status | source runs |', '|---|---|---|---|---|---|']
prev = [l for l in old.split('\n') if l.startswith('| ') and 'file:line' not in l and not l.startswith('|---')]
lines += prev
for t in trace:
    lines.append(f"| {t[0]}:{t[1]} | {t[2]} | {t[3]} | {t[4]} | {t[5]} | {t[6]} |")
# drop stale rows whose rendered string no longer occurs in their file; dedupe
seen=set(); keep=[]
for l in lines:
    if l.startswith('| ') and 'file:line' not in l and not l.startswith('|---'):
        c=[x.strip() for x in l.strip('|').split('|')]
        fn=c[0].split(':')[0]; txt=(root/'paper/sections'/fn).read_text()
        if c[3] not in txt: continue
        k=(fn,c[1],c[2],c[3])
        if k in seen: continue
        seen.add(k)
    keep.append(l)
lines=keep
(root/'paper/NUMBER_TRACE.md').write_text('\n'.join(lines) + '\n')
print(len(trace), 'substitutions')
